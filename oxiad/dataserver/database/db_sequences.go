const maxSequence = uint64(math.MaxUint64)

// sequenceValueDigits is the length of a value in a sequence key, %020d.
const sequenceValueDigits = 20

func generateUniqueKeyFromSequences(batch kvstore.WriteBatch, req *proto.PutRequest,
	features feature.Checker) (string, error) {
	if req.PartitionKey == nil {
		// All the keys need to be in same shard to guarantee atomicity
		return "", errors.Wrap(errs.ErrDBInvalidSequentialKey, "missing partition key")
	}

	if req.ExpectedVersionId != nil {
		// Cannot set an expected version id when key is sequential
		return "", errs.ErrDBBadVersion
	}

	parts, err := findCurrentLastKeyInSequence(batch, req, features)
	if err != nil {
		return "", err
	}

	newKey := req.Key
	for idx := range max(len(req.SequenceKeyDelta), len(parts)) {
		// A part of the sequence without a delta keeps its value
		var delta uint64
		if idx < len(req.SequenceKeyDelta) {
			delta = req.SequenceKeyDelta[idx]
		}

		if idx == 0 && delta == 0 {
			// The first delta in the list must be strictly > 0
			// Otherwise there would be possibility of reordering of keys
			return "", errors.Wrap(errs.ErrDBInvalidSequentialKey, "the first delta must be above zero")
		}

		var lastValue uint64
		if idx < len(parts) {
			var err error
			if lastValue, err = parseSequenceValue(parts[idx], features); err != nil {
				// The last key of the prefix was not generated by the
				// sequence, e.g. a plain put of "prefix-"
				return "", errors.Wrapf(errs.ErrDBInvalidSequentialKey, "a key is not part of the sequence: sequence %q: %v", parts[idx], err)
			}
		} else {
			// There are additional sequences
			lastValue = 0
		}

		if delta >= maxSequence-lastValue {
			// Past the max, the cumulative value would wrap: the generated key
			// would sort below the current tail and could collide with an
			// earlier entry. At the max, the next put wouldn't find the key,
			// since the last key is looked up below "<prefix>-<max>".
			return "", errors.Wrap(errs.ErrDBInvalidSequentialKey, "the sequence overflows")
		}
		newKey = fmt.Sprintf("%s-%020d", newKey, lastValue+delta)
	}

	return newKey, nil
}

// parseSequenceValue parses a part of the last key of a sequence. With
// FEATURE_SEQUENCE_LAST_KEY_SEPARATOR, the part must be a value as the sequence
// formats it, of 20 digits: fmt.Sscanf alone also accepts a part that only
// starts with digits, e.g. "05" in a plain key "<prefix>-05". The sequence would
// continue below such a key, which then stays its last key, so every later put
// would get the same key, and replace the record of the previous one.
func parseSequenceValue(part string, features feature.Checker) (uint64, error) {
	if features.IsFeatureEnabled(proto.Feature_FEATURE_SEQUENCE_LAST_KEY_SEPARATOR) && !isSequenceValue(part) {
		return 0, errors.Errorf("not a value of %d digits", sequenceValueDigits)
	}
	var value uint64
	_, err := fmt.Sscanf(part, "%020d", &value)
	return value, err
}

func isSequenceValue(part string) bool {
	if len(part) != sequenceValueDigits {
		return false
	}
	for i := 0; i < len(part); i++ {
		if part[i] < '0' || part[i] > '9' {
			return false
		}
	}
	return true
}

func findCurrentLastKeyInSequence(wb kvstore.WriteBatch, req *proto.PutRequest,
	features feature.Checker) ([]string, error) {
	prefixKey := req.Key
	maxKey := fmt.Sprintf("%s-%020d", prefixKey, maxSequence)
	lastKeyInSequence, err := wb.FindLower(maxKey)
	if err != nil && !errors.Is(err, errs.ErrDBKeyNotFound) {
		return nil, err
	}

	keysPrefix := prefixKey + "-"
	if !features.IsFeatureEnabled(proto.Feature_FEATURE_SEQUENCE_LAST_KEY_SEPARATOR) {
		// Like the versions without the feature, also take as the last key a
		// plain key below an empty sequence that only starts with prefixKey,
		// e.g. "<prefixKey>+x-<n>": every replica must generate the same keys.
		keysPrefix = prefixKey
	}
	if errors.Is(err, errs.ErrDBKeyNotFound) || !strings.HasPrefix(lastKeyInSequence, keysPrefix) {
		lastKeyInSequence = ""
	} else {
		lastKeyInSequence = strings.TrimPrefix(lastKeyInSequence, prefixKey)
	}

	parts := strings.Split(lastKeyInSequence, "-")[1:]
	if len(parts) > len(req.SequenceKeyDelta) &&
		!features.IsFeatureEnabled(proto.Feature_FEATURE_SEQUENCE_KEY_VALIDATION) {
		// The request has less sequence key deltas than there are already
		// available in the sequence. With the feature, the missing deltas
		// are 0 instead: every replica must generate the same keys.
		return nil, errors.Wrap(errs.ErrDBInvalidSequentialKey, "missing sequence deltas")
	}
	return parts, nil
}
